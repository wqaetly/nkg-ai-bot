export type AppPlatform =
  | "windows"
  | "macos"
  | "linux"
  | "android"
  | "ios";

export type RuntimeBackendKind = "node-sidecar" | "in-process";

/** Product-level execution mode; platform only constrains valid choices. */
export type RuntimeMode = "portable" | "desktop-power";

export type RuntimeRouterState =
  | "idle"
  | "starting"
  | "ready"
  | "stopping"
  | "failed";

export interface RuntimeBackend {
  readonly kind: RuntimeBackendKind;
  start(): Promise<void>;
  request(path: string, init?: RequestInit): Promise<Response>;
  stop(): Promise<void>;
}

export type RuntimeBackendFactory = () =>
  | RuntimeBackend
  | Promise<RuntimeBackend>;

export interface RuntimeRouterOptions {
  platform: AppPlatform;
  /** Defaults to portable on all five supported platforms. */
  mode?: RuntimeMode;
  portable?: RuntimeBackendFactory;
  desktopPower?: RuntimeBackendFactory;
  /** @deprecated Use `desktopPower`. */
  desktop?: RuntimeBackendFactory;
  /** @deprecated Use `portable`. */
  mobile?: RuntimeBackendFactory;
}

export interface RuntimeRouterSnapshot {
  platform: AppPlatform;
  mode: RuntimeMode;
  backend: RuntimeBackendKind;
  state: RuntimeRouterState;
  /** Increments after each successfully started backend instance. */
  generation: number;
  error?: Error;
}

export interface SidecarDescriptor {
  /** The sidecar must bind to a loopback HTTP address. */
  baseUrl: string;
  /** Ephemeral per-launch bearer token generated by the native host. */
  token: string;
}

export interface SidecarLauncher {
  start(): Promise<SidecarDescriptor>;
  stop(): Promise<void>;
}

export type RuntimeHttpHandler = (request: Request) => Promise<Response>;

export interface NodeSidecarBackendOptions {
  launcher: SidecarLauncher;
  fetch?: typeof globalThis.fetch;
  /** Header understood by the packaged sidecar. Defaults to Authorization. */
  tokenHeader?: string;
}

export interface InProcessBackendOptions {
  createHandler: () => RuntimeHttpHandler | Promise<RuntimeHttpHandler>;
  /** Synthetic origin used only to construct a standards-compliant Request. */
  origin?: string;
}

export interface FlowInvokeOptions {
  flowVersion?: string;
  traceId?: string;
  signal?: AbortSignal;
  envOverrides?: {
    variables?: Record<string, JsonValue>;
    secrets?: Record<string, string>;
  };
  nodeOverrides?: Record<string, {
    config?: Record<string, unknown>;
    label?: string;
    position?: { x: number; y: number };
  }>;
  /** Called as soon as a streaming response exposes its run identity. */
  onRunStarted?: (runId: string) => void;
}

export type JsonPrimitive = string | number | boolean | null;
export type JsonValue =
  | JsonPrimitive
  | JsonValue[]
  | { [key: string]: JsonValue };

export interface RuntimeErrorBody {
  code?: string;
  message: string;
  details?: unknown;
}

export interface FlowInvokeResult {
  runId: string;
  flowId: string;
  flowVersion: string;
  status: string;
  output: unknown;
  error: RuntimeErrorBody | null;
  nodeId?: string;
}

export interface RunRecord {
  runId: string;
  flowId: string;
  flowVersion: string;
  status: string;
  [key: string]: unknown;
}

export interface NodeEvent {
  eventId: string;
  runId: string;
  flowId: string;
  flowVersion: string;
  seq: number;
  timestamp: string;
  kind: string;
  payload: unknown;
  nodeId?: string;
  nodeVersion?: string;
  attempt?: number;
  portId?: string;
  streamId?: string;
  traceId?: string;
  parentEventId?: string;
}

export class RuntimeRouteError extends Error {
  readonly status: number;
  readonly code?: string;
  readonly details?: unknown;

  constructor(message: string, options: {
    status: number;
    code?: string;
    details?: unknown;
  }) {
    super(message);
    this.name = "RuntimeRouteError";
    this.status = options.status;
    if (options.code !== undefined) this.code = options.code;
    if (options.details !== undefined) this.details = options.details;
  }
}

export type RuntimeTransportPhase = "request" | "stream";

/**
 * A transport-level interruption whose failed operation must not be replayed
 * automatically. The next explicit user operation may recover the backend.
 */
export class RuntimeTransportError extends Error {
  readonly code = "runtime.transport_interrupted";
  readonly recoverable = true;
  readonly automaticRetry = false;
  readonly backend: RuntimeBackendKind;
  readonly phase: RuntimeTransportPhase;
  readonly requestMayHaveExecuted: boolean;

  constructor(message: string, options: {
    backend: RuntimeBackendKind;
    phase: RuntimeTransportPhase;
    requestMayHaveExecuted: boolean;
    cause?: unknown;
  }) {
    super(message);
    this.name = "RuntimeTransportError";
    if (options.cause !== undefined) {
      Object.defineProperty(this, "cause", {
        value: options.cause,
        configurable: true,
      });
    }
    this.backend = options.backend;
    this.phase = options.phase;
    this.requestMayHaveExecuted = options.requestMayHaveExecuted;
  }
}
